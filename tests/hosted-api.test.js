import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import {once} from 'node:events';
import {createHash} from 'node:crypto';
import {mkdtemp,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {createApi} from '../server/api.js';
import {createAccess,accountNamespace} from '../server/access.js';
import {createKnowledgeStore} from '../server/knowledge.js';
test('hosted HTTP routes isolate jobs and knowledge using authenticated identity',async t=>{
  const directory=await mkdtemp(join(tmpdir(),'closet-hosted-test-')),calls=[];
  const origin='https://study.example.com',users=JSON.stringify(['one','two'].map((code,i)=>({id:`p0${i+1}`,tokenHash:createHash('sha256').update(code).digest('hex')})));
  const access=createAccess({origin,secret:'test-secret-that-is-long-enough-0123456789',users});
  const knowledge=createKnowledgeStore({storageDir:join(directory,'knowledge')});
  const api=createApi({storageDir:directory,access,services:{recognize:async()=>({data:{name:'Test top'}})},knowledgeStore:{...knowledge,list:async owner=>{calls.push(owner);return knowledge.list(owner);}}});
  const server=http.createServer(api.middleware);server.listen(0,'127.0.0.1');await once(server,'listening');
  t.after(async()=>{api.close();await new Promise(resolve=>server.close(resolve));await rm(directory,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${server.address().port}`;
  const req=(path,{body,cookie,method=body?'POST':'GET'}={})=>new Promise((resolve,reject)=>{
    const request=http.request(base+path,{method,headers:{host:'study.example.com',origin,'content-type':'application/json',...(cookie?{cookie}:{})}},response=>{let text='';response.on('data',chunk=>text+=chunk);response.on('end',()=>resolve({status:response.statusCode,headers:{get:name=>[].concat(response.headers[name]||[]).join('')},json:async()=>JSON.parse(text)}));});
    request.on('error',reject);request.end(body?JSON.stringify(body):undefined);
  });
  assert.equal((await req('/status')).status,401);
  const login=async code=>{const response=await req('/session/login',{body:{code}});assert.equal(response.status,200);return response.headers.get('set-cookie').split(';')[0];};
  const one=await login('one'),two=await login('two');
  const created=await req('/jobs',{cookie:one,body:{image:'data:image/jpeg;base64,YQ==',provider:'openai',wardrobeId:'account-p02'}});assert.equal(created.status,202);const job=await created.json();
  assert.equal((await req(`/jobs/${job.id}`,{cookie:two})).status,404);
  assert.equal((await req(`/jobs/${job.id}`,{cookie:two,method:'DELETE'})).status,404);
  assert.equal((await req(`/jobs/${job.id}`,{cookie:one})).status,200);
  assert.equal((await req('/knowledge/list',{cookie:one,body:{wardrobeId:'account-p02'}})).status,200);
  assert.deepEqual(calls,[accountNamespace('p01')]);
  await knowledge.upsert(accountNamespace('p01'),{title:'Private p01 note',content:'Only participant one owns this document.',source:'test'},{lexicalOnly:true});
  const ownDocs=await (await req('/knowledge/list',{cookie:one,body:{}})).json();
  const otherDocs=await (await req('/knowledge/list',{cookie:two,body:{wardrobeId:accountNamespace('p01')}})).json();
  assert.match(JSON.stringify(ownDocs),/Private p01 note/);
  assert.doesNotMatch(JSON.stringify(otherDocs),/Private p01 note/);
  assert.equal((await req('/learning/export',{cookie:one})).status,403);
  assert.equal((await req('/depop/shop',{cookie:one})).status,403);
});
